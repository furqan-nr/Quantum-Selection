def utc(ts):
    return dt.datetime.fromtimestamp(ts, dt.timezone.utc)


def first_last(ver, passes):
    ts = []
    for ps in passes:
        for f in glob.glob(str(ROOT / "phase_e" / "data" / "runs" / f"w{ver}_t{ver}" / f"pass{ps}" / "files" / "*.jsonl")):
            for line in open(f):
                try:
                    r = json.loads(line)
                except ValueError:
                    continue
                if "t" in r:
                    ts.append(r["t"])
    return utc(min(ts)), utc(max(ts))


