"""Generate the Phase D backported detecting tests (PREREGISTRATION_PHASE_D.md, Section 5).

For an 'upstream_method' backport the generated module contains, VERBATIM, the decorator lines and body of each
fix-release test method (copied from the fix release's sdist, whose SHA-256 is checked against PyPI), placed in a
subclass of the BUGGY release's own test class (so class helpers, setUp and attributes come from the version under
test). Inherited tests are hidden (set to None, which unittest/pytest skip), so the module runs only the backported
methods. Module-level names that the methods use are imported exactly as the fix-release module binds them
(relative imports made absolute); module-level helpers defined in the test module are taken from the buggy
release's module. For the 'added_file' backport (D2) the added test file is copied unchanged.

Run once, before the record (outputs are frozen in phase_d/backports/):
    python phase_d/tools/make_backports.py --sdist 2.2.3=/tmp/pd/sd/qiskit-2.2.3.tar.gz ... (one per source version)
The sdists are not part of the repository; their SHA-256 values are in phase_d/config/phase_d_config.json.
"""
from __future__ import annotations

import argparse
import ast
import builtins
import hashlib
import json
import tarfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]


def _module_bindings(tree: ast.Module, package: str) -> dict[str, str]:
    """name -> source line that binds it at module level (imports only; defs/assigns map to '__upstream__')."""
    out: dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, ast.Import):
            for a in node.names:
                top = (a.asname or a.name).split(".")[0]
                out[top] = f"import {a.name}" + (f" as {a.asname}" if a.asname else "")
        elif isinstance(node, ast.ImportFrom):
            mod = node.module or ""
            if node.level:
                parts = package.split(".")
                base = parts[: len(parts) - (node.level - 1)]
                mod = ".".join(base + ([mod] if mod else []))
            for a in node.names:
                out[a.asname or a.name] = f"from {mod} import {a.name}" + (f" as {a.asname}" if a.asname else "")
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            out.setdefault(node.name, "__upstream__")
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    out.setdefault(t.id, "__upstream__")
    return out


def generate_upstream(event: dict, sdist: Path, expected_sha: str) -> str:
    sha = hashlib.sha256(sdist.read_bytes()).hexdigest()
    if sha != expected_sha:
        raise SystemExit(f"{sdist}: sha256 {sha} != frozen {expected_sha}")
    bp = event["backport"]
    ver = bp["source_version"]
    member = f"qiskit-{ver}/{bp['source_member']}"
    with tarfile.open(sdist) as tf:
        src = tf.extractfile(member).read().decode("utf-8")
    member_sha = hashlib.sha256(src.encode("utf-8")).hexdigest()
    lines = src.splitlines()
    tree = ast.parse(src)
    modpath = bp["source_member"][:-3].replace("/", ".")          # test.python.transpiler.test_x
    package = modpath.rsplit(".", 1)[0]
    binds = _module_bindings(tree, package)
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == bp["class"])
    chunks, used, spans = [], set(), []
    for name in bp["methods"]:
        fn = next(f for f in cls.body if isinstance(f, ast.FunctionDef) and f.name == name)
        start = min([d.lineno for d in fn.decorator_list] + [fn.lineno])
        chunks.append("\n".join(lines[start - 1: fn.end_lineno]))
        spans.append(f"{name}: lines {start}-{fn.end_lineno}")
        for d in fn.decorator_list:
            used |= {n.id for n in ast.walk(d) if isinstance(n, ast.Name)}
        used |= {n.id for n in ast.walk(fn) if isinstance(n, ast.Name)}
    for d in cls.decorator_list:
        used |= {n.id for n in ast.walk(d) if isinstance(n, ast.Name)}
    imports, upstream_names = [], []
    for n in sorted(used):
        if n in binds and binds[n] != "__upstream__":
            imports.append(binds[n])
        elif n in binds:
            upstream_names.append(n)
        # names bound only locally inside the method, or builtins, need nothing
    imports = sorted(set(imports))
    decos = "\n".join("@" + ast.unparse(d) for d in cls.decorator_list)
    hdr = [
        f'"""Phase D backport for event {event["event_id"]} ({event["fault"]}).',
        "",
        "GENERATED by phase_d/tools/make_backports.py; do not edit (frozen, PREREGISTRATION_PHASE_D.md Section 5).",
        f"Source: qiskit-{ver}.tar.gz (sha256 {sha}),",
        f"        member {member} (sha256 {member_sha}),",
        f"        class {bp['class']}; " + "; ".join(spans) + ". Method text below is verbatim.",
        f"Logical location (used for ordering and the cost estimator): {event['logical_file']}::{bp['class']}",
        "Class context: the release under test's own class of the same name (helpers, setUp); inherited tests hidden.",
        '"""',
        "# pylint: disable=all",
    ]
    body = hdr + imports + [f"import {modpath} as _phase_d_upstream", ""]
    for n in upstream_names:
        body.append(f"{n} = _phase_d_upstream.{n}")
    body += ["", ""]
    if decos:
        body.append(decos)
    body.append(f"class {bp['class']}(_phase_d_upstream.{bp['class']}):")
    body.append(f'    """Backported fix-release method(s) of {bp["class"]} (verbatim)."""')
    body.append("")
    body.append("\n\n".join(chunks))
    body += [
        "",
        "",
        f"for _n in dir({bp['class']}):",
        f"    if _n.startswith(\"test\") and _n not in {bp['class']}.__dict__:",
        f"        setattr({bp['class']}, _n, None)  # hide inherited tests: only the backported methods run",
        "",
    ]
    return "\n".join(body)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdist", action="append", default=[], help="VERSION=path/to/qiskit-VERSION.tar.gz")
    args = ap.parse_args()
    sd = dict(s.split("=", 1) for s in args.sdist)
    cfg = json.loads((REPO / "phase_d/config/phase_d_config.json").read_text())
    ledger = json.loads((REPO / "phase_d/events/phase_d_events.json").read_text())
    for ev in ledger["events"]:
        out = REPO / ev["backport_file"]
        bp = ev["backport"]
        if bp["kind"] == "added_file":
            src = (REPO / bp["source"]).read_text()
            text = (f'"""Phase D backport for event {ev["event_id"]}: ADDED test (not in Qiskit), copied unchanged from\n'
                    f'{bp["source"]} (written 2026-10-18, before the record).\n'
                    f'Logical location (ordering, estimator): {ev["logical_file"]}"""\n' + src)
        else:
            v = bp["source_version"]
            text = generate_upstream(ev, Path(sd[v]), cfg["versions"][v]["sdist"]["sha256"])
        out.write_text(text, newline="\n")
        print("wrote", out.relative_to(REPO))


if __name__ == "__main__":
    main()
